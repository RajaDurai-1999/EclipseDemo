package Operators;

public class Assignment {

	public static void main(String[] args) {
		 int n = 10;

	        n += 5;   
	        System.out.println("+= : " + n);

	        n -= 3;   
	        System.out.println("-= : " + n);

	        n *= 2;  
	        System.out.println("*= : " + n);

	        n /= 4;   
	        System.out.println("/= : " + n);

	        n %= 3;   
	        System.out.println("%= : " + n);

	}

}
